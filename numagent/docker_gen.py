from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path
from typing import Tuple

from .models import BuildSystem, DetectResult, Language

OUT_DIR = ".numagent"


@dataclass
class DockerArtifacts:
    dockerfile: str
    run_sh: str
    dockerignore: str
    image_tag: str


def _slug(repo_path: str) -> str:
    name = Path(repo_path).name.lower()
    name = re.sub(r"[^a-z0-9_.-]", "-", name).strip("-.") or "repo"
    return f"numagent/{name}:latest"


_RUN_HEADER = "#!/usr/bin/env bash\nset -euo pipefail\n"


def _base_and_setup(det: DetectResult) -> Tuple[str, str]:
    """Return (FROM image, extra Dockerfile setup lines) for the build system."""
    bs, lang = det.build_system, det.language
    apt = "RUN apt-get update && apt-get install -y --no-install-recommends {pkgs} \\\n    && rm -rf /var/lib/apt/lists/*"

    if bs == BuildSystem.PIP:
        return "python:3.11-slim", "RUN python -m pip install --upgrade pip"

    if bs in (BuildSystem.CMAKE, BuildSystem.MAKE):
        if lang == Language.FORTRAN:
            # gcc image already ships gfortran, g++, make.
            pkgs = "cmake" if bs == BuildSystem.CMAKE else ""
            setup = apt.format(pkgs=pkgs) if pkgs else "# toolchain already in gcc image"
            return "gcc:13", setup
        pkgs = "build-essential cmake" if bs == BuildSystem.CMAKE else "build-essential"
        return "debian:bookworm-slim", apt.format(pkgs=pkgs)

    if bs == BuildSystem.FPM:
        # gcc image has gfortran; fetch the prebuilt fpm binary release.
        fpm = ("ARG FPM_VERSION=0.13.0\n"
               "RUN apt-get update && apt-get install -y --no-install-recommends curl \\\n"
               "    && curl -fsSL -o /usr/local/bin/fpm "
               "https://github.com/fortran-lang/fpm/releases/download/v${FPM_VERSION}/"
               "fpm-${FPM_VERSION}-linux-x86_64-gcc-12 \\\n"
               "    && chmod +x /usr/local/bin/fpm && rm -rf /var/lib/apt/lists/*")
        return "gcc:13", fpm

    return "debian:bookworm-slim", "# unknown build system"


def _run_body(det: DetectResult) -> str:
    bs = det.build_system
    if bs == BuildSystem.PIP:
        return (
            'echo "== build =="\n'
            "python -m pip install -e . || python -m pip install .\n"
            "python -m pip install pytest\n"
            'echo "== test =="\n'
            "python -m pytest -q\n"
        )
    if bs == BuildSystem.CMAKE:
        return (
            'echo "== build =="\n'
            "cmake -S . -B build\n"
            "cmake --build build -j\n"
            'echo "== test =="\n'
            "cd build && ctest --output-on-failure\n"
        )
    if bs == BuildSystem.MAKE:
        return (
            'echo "== build =="\n'
            "make\n"
            'echo "== test =="\n'
            'if make -n test >/dev/null 2>&1; then make test; \\\n'
            'elif make -n check >/dev/null 2>&1; then make check; \\\n'
            'else echo "no test/check target in Makefile"; fi\n'
        )
    if bs == BuildSystem.FPM:
        return (
            'echo "== build =="\nfpm build\n'
            'echo "== test =="\nfpm test\n'
        )
    return 'echo "unknown build system; nothing to do" >&2\nexit 1\n'


def generate(repo_path: str, det: DetectResult) -> DockerArtifacts:
    base, setup = _base_and_setup(det)
    dockerfile = (
        f"# generated by numagent for a {det.language.value} / {det.build_system.value} repo\n"
        f"FROM {base}\n"
        f"{setup}\n"
        "WORKDIR /repo\n"
        "COPY . /repo\n"
        'CMD ["bash", ".numagent/run.sh"]\n'
    )
    run_sh = _RUN_HEADER + _run_body(det)
    dockerignore = ".git\n.numagent_venv\nbuild\n_build\n**/__pycache__\n*.egg-info\n"
    return DockerArtifacts(dockerfile, run_sh, dockerignore, _slug(repo_path))


def write(artifacts: DockerArtifacts, repo_path: str) -> str:
    """Write the artifacts into <repo>/.numagent and a .dockerignore at the root.
    Returns the .numagent dir path."""
    out = Path(repo_path) / OUT_DIR
    out.mkdir(parents=True, exist_ok=True)
    (out / "Dockerfile").write_text(artifacts.dockerfile)
    sh = out / "run.sh"
    sh.write_text(artifacts.run_sh)
    sh.chmod(0o755)
    (Path(repo_path) / ".dockerignore").write_text(artifacts.dockerignore)
    return str(out)
